public enum StatType
{
    MoveSpeed,          // 이동 속도
    MaxHp,              // 최대 체력
    AbsorbGrowSpeed,    // 흡수 영역 확장 속도
    RushDuration,       // 돌진 지속 시간
    AbsorbRadius,       // 흡수 범위 (최소/최대 반지름)
    AbsorbCooldown,     // 흡수 쿨타임
    RushCooldown,       // 돌진 쿨타임
    RushInvincible,     // 돌진 무적 시간
    RushSpeed,          // 돌진 속도
    KnockbackForce,     // 적 사망 시 넉백 힘
    ChainDamage,        // 연쇄 충돌 피해 (드롭킥 피해 포함)
    ScoreMultiplier,    // 점수 배율
    RushCount,          // 돌진 횟수
    SpawnRate,          // 적 생성 속도 배율
    RushDistance        // 유효 돌진 거리 배율
}
